from guide_lib import Q


def V(body, expect):
    return {"lang": "verilog", "code": "module t;\n" + body.strip("\n") + "\nendmodule\n", "expect": expect}


def P(code, expect):
    return {"lang": "py", "code": code, "expect": expect}


def vq(stem, right, wrong, why, body, expect):
    """預測模擬輸出的題：body 是 module t 裡面的內容；題幹下附上同一段程式。"""
    return Q(stem, right, wrong, why, verify=V(body, expect), code=body.strip("\n"), lang="verilog")


